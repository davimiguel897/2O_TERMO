-----------------------------------------------------------------

-- RESUMO SOBRE O CONCEITO DE NORMALIZAÇÃO

-- OBS:
-- ESTRUTURA DE NORMALIZAÇÃO 1FN
-- FOI IDENTIFICADO NOS GRUPOS REPETIDOS COMO PRODUTO1, PRODUTO2 E PRODUTO3
-- A 1FN FAZ SENTIDO PORQUE UM PEDIDO PODE POSSUIR QUALQUER QUANTIDADE SEM CRIAR NOVAS COLUNAS
-- FOI GERADO AS TABELAS PEDIDO E ITEM_PEDIDO PARA ESSA NORMALIZAÇÃO
-- ESTRUTURA DE NORMALIZAÇÃO 2FN
-- OS DADOS DO CLIENTE NÃO PERTECEM AO PEDIDO. ELES DESCREVEM O CLIENTE. O NOME DA CATEGORIA TAMBÉM NÃO DEVE SER REPETIDO EM CADA PRODUTO
-- SEPARAÇÃO DAS TABELAS CLIENTE, PRODUTO E CATEGORIA QUE ENVOLVE CHAVE PRIMÁRIAS OU CHAVE COMPOSTAS
-- EM UMA CHAVE COMPOSTA OS ATRIBUTOS COMUNS DEVEM DEPENDER DA CHAVE PRIMÁRIA OU INTEIRA

-- ESTRUTURA DE NORMALIZAÇÃO 3FN
-- NOME CATEGORIA QUE DEPENDE DE ID_CATEGORIA. PORTANTO, DEVE ESTAR EM UMA TABELA

-- RESUMO:
-- 1FN RESOLVE
-- 2FN REMOVE DEPENDÊNCIAS PARCIAIS DE CHAVES COMPOSTAS
-- 3FN REMOVE DEPENDÊNCIAS INDEVIDAS ENTRE ATRIBUTOS NÃO-CHAVE PRIMÁRIAS

